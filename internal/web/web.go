//go:embed templates/*.html
var templateFS embed.FS

//go:embed htmx.min.js
var htmxJS []byte

// Config selects viewer behavior. The viewer runs only when the caller
// (`cmd/cask web`) constructs it — there is no Enabled switch
// (viewer-security §3).
type Config struct {
	StartupToken string // generated at startup, printed once, admin role
	RoleTokens   map[string]string
	Secure       bool // serve Secure cookies (HTTPS)
}

// Server is the viewer: login, sessions, role authorization, CSRF, and the
// hypermedia pages/fragments.
type Server struct {
	store         *fs.Backend
	cfg           Config
	sessions      *sessions
	loginThrottle *throttle
	tmpl          *template.Template
}

// New builds the viewer over the raw store. StartupToken is generated by the
// caller (cmd/cask) and printed once at startup.
func New(store *fs.Backend, cfg Config) (*Server, error) {
	tmpl, err := template.New("viewer").Funcs(template.FuncMap{
		"shortDigest": shortDigest,
	}).ParseFS(templateFS, "templates/*.html")
	if err != nil {
		return nil, fmt.Errorf("parse templates: %w", err)
	}
	return &Server{
		store:         store,
		cfg:           cfg,
		sessions:      newSessions(),
		loginThrottle: newThrottle(5, time.Minute),
		tmpl:          tmpl,
	}, nil
}

// Handler returns the viewer routes with the fixed middleware order:
// auth (session) → role → CSRF (mutations) → handler. Login is public.
func (s *Server) Handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /viewer/login", s.loginPage)
	mux.HandleFunc("POST /viewer/login", s.loginPost)
	mux.HandleFunc("GET /viewer/static/htmx.min.js", s.htmx)
	mux.HandleFunc("GET /viewer/", func(w http.ResponseWriter, r *http.Request) {
		// Never let a token in the URL leak via Referer.
		w.Header().Set("Referrer-Policy", "no-referrer")
		if token := strings.TrimSpace(r.URL.Query().Get("token")); token != "" {
			s.loginToken(w, r, token)
			return
		}
		if _, ok := s.sessions.get(sessionID(r)); !ok {
			http.Redirect(w, r, "/viewer/login", http.StatusSeeOther)
			return
		}
		s.require(RoleViewer, s.dashboard)(w, r)
	})
	mux.HandleFunc("GET /viewer/dashboard", s.require(RoleViewer, s.dashboardFragment))
	mux.HandleFunc("GET /viewer/objects", s.require(RoleViewer, s.objects))
	mux.HandleFunc("GET /viewer/objects/{hash}", s.require(RoleViewer, s.objectDetail))
	mux.HandleFunc("GET /viewer/objects/{hash}/raw", s.require(RoleViewer, s.objectRaw))
	mux.HandleFunc("POST /viewer/objects/{hash}/verify", s.require(RoleOperator, s.verifyFragment))
	mux.HandleFunc("POST /viewer/objects/{hash}/delete", s.require(RoleAdmin, s.deleteFragment))
	mux.HandleFunc("GET /viewer/gc", s.require(RoleAdmin, s.gcPage))
	mux.HandleFunc("POST /viewer/gc", s.require(RoleAdmin, s.gcFragment))
	return mux
}

// Roles (viewer-security §8).
const (
	RoleViewer   = "viewer"
	RoleOperator = "operator"
	RoleAdmin    = "admin"
)

// require enforces: valid session (401 empty), sufficient role (403 empty),
// CSRF on mutations (403 empty). Never discloses existence.
func (s *Server) require(role string, next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		sess, ok := s.sessions.get(sessionID(r))
		if !ok {
			w.WriteHeader(http.StatusUnauthorized) // empty body
			return
		}
		if sess.Role != role && !roleAllows(sess.Role, role) {
			w.WriteHeader(http.StatusForbidden) // empty body
			return
		}
		if !csrfOK(r, sess) {
			slog.Warn("viewer csrf rejected", "path", r.URL.Path)
			w.WriteHeader(http.StatusForbidden) // empty body
			return
		}
		next(w, r)
	}
}

// roleAllows reports whether the session role satisfies the required role
// (admin ⊃ operator ⊃ viewer).
func roleAllows(sessionRole, required string) bool {
	rank := map[string]int{RoleViewer: 1, RoleOperator: 2, RoleAdmin: 3}
	return rank[sessionRole] >= rank[required]
}

// --- login ---

func (s *Server) loginPage(w http.ResponseWriter, r *http.Request) {
	s.render(w, "login", nil)
}

// loginPost validates the submitted token against the startup token (admin)
// or the configured per-role tokens, throttles failures per IP (5/min with
// backoff, viewer-security §5), and issues a session cookie.
func (s *Server) loginToken(w http.ResponseWriter, r *http.Request, token string) {
	ip := callerIP(r)
	if !s.loginThrottle.allow(ip) {
		slog.Warn("viewer login throttled", "ip", ip)
		http.Error(w, "too many login attempts", http.StatusTooManyRequests)
		return
	}
	role, ok := s.resolveToken(token)
	if !ok {
		// The attempt was already recorded by allow.
		slog.Warn("viewer login failed", "ip", ip) // token value never logged
		http.Error(w, "invalid token", http.StatusUnauthorized)
		return
	}
	s.loginThrottle.reset(ip)
	sess, err := s.sessions.create(role)
	if err != nil {
		slog.Error("viewer login", "err", err)
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}
	setSessionCookie(w, sess, s.cfg.Secure)
	slog.Info("viewer login", "role", role, "ip", ip)
	http.Redirect(w, r, "/viewer/", http.StatusSeeOther)
}

func (s *Server) loginPost(w http.ResponseWriter, r *http.Request) {
	s.loginToken(w, r, r.FormValue("token"))
}

// resolveToken matches token against the startup token (admin role) and the
// configured per-role tokens (token → role) using constant-time comparison.
// An empty token never matches, so a mis-configured empty token cannot grant
// a role (viewer-security §5).
func (s *Server) resolveToken(token string) (string, bool) {
	if token == "" {
		return "", false
	}
	if subtle.ConstantTimeCompare([]byte(token), []byte(s.cfg.StartupToken)) == 1 {
		return RoleAdmin, true
	}
	for tok, role := range s.cfg.RoleTokens {
		if subtle.ConstantTimeCompare([]byte(tok), []byte(token)) == 1 {
			return role, true
		}
	}
	return "", false
}

// --- dashboard ---

func (s *Server) dashboard(w http.ResponseWriter, r *http.Request) {
	s.render(w, "dashboard", s.dashboardData(r.Context()))
}

func (s *Server) dashboardFragment(w http.ResponseWriter, r *http.Request) {
	s.render(w, "dashboard_panels", s.dashboardData(r.Context()))
}

type dashboardData struct {
	ObjectCount int64
	TotalSize   int64
	Sample      []objectRow
	HasSample   bool
}

type objectRow struct {
	Digest string
	Short  string
	Type   string
	Size   int64
}

func (s *Server) dashboardData(ctx context.Context) dashboardData {
	st, err := s.store.Stats(ctx)
	if err != nil {
		st = &cas.Stats{}
	}
	d := dashboardData{ObjectCount: st.ObjectCount, TotalSize: st.TotalSize}
	digests, err := s.store.List(ctx)
	if err != nil {
		return d
	}
	for _, h := range index.Paginate(digests, 0, 10) {
		d.Sample = append(d.Sample, objectRow{h.String(), shortDigest(h), s.objectType(ctx, h), s.objectSize(ctx, h)})
	}
	d.HasSample = len(d.Sample) > 0
	return d
}

// --- objects list ---

func (s *Server) objects(w http.ResponseWriter, r *http.Request) {
	q := strings.TrimSpace(r.URL.Query().Get("q"))
	digests, err := s.store.List(r.Context())
	if err != nil {
		http.Error(w, "list failed", http.StatusInternalServerError)
		return
	}
	var rows []objectRow
	for _, h := range digests {
		typ := ""
		if q != "" {
			typ = s.objectType(r.Context(), h)
			if !strings.Contains(h.String(), q) && !strings.Contains(typ, q) {
				continue
			}
		}
		rows = append(rows, objectRow{h.String(), shortDigest(h), typ, s.objectSize(r.Context(), h)})
	}
	data := struct {
		Query   string
		Objects []objectRow
		HasAny  bool
	}{q, rows, len(rows) > 0}
	if r.Header.Get("HX-Request") == "true" {
		s.render(w, "object-table-fragment", data) // htmx search/refresh swap
		return
	}
	s.render(w, "objects", data)
}

// --- object detail ---

func (s *Server) objectDetail(w http.ResponseWriter, r *http.Request) {
	h, ok := parseDigest(w, r)
	if !ok {
		return
	}
	data, err := s.readN(r.Context(), h, typePrefixLimit)
	if err != nil {
		http.Error(w, "not found", http.StatusNotFound)
		return
	}
	typ := index.EnvelopeType(data)
	s.render(w, "object", struct {
		Digest    string
		Algorithm string
		Type      string
		Size      int64
		CSRF      string
		Role      string
	}{h.String(), sha256.Name, typ, s.objectSize(r.Context(), h), s.csrfFor(r), s.roleFor(r)})
}

func (s *Server) objectRaw(w http.ResponseWriter, r *http.Request) {
	h, ok := parseDigest(w, r)
	if !ok {
		return
	}
	data, truncated, err := s.readPreview(r.Context(), h)
	if err != nil {
		http.Error(w, "not found", http.StatusNotFound)
		return
	}
	note := ""
	if truncated {
		note = fmt.Sprintf("preview truncated at %d KiB of %d bytes", previewLimit>>10, s.objectSize(r.Context(), h))
	}
	s.render(w, "hexdump", struct {
		Rows []dumpRow
		Note string
	}{hexdump(data), note})
}

func (s *Server) verifyFragment(w http.ResponseWriter, r *http.Request) {
	h, ok := parseDigest(w, r)
	if !ok {
		return
	}
	// Every admin action is audit-logged (viewer-security §"audit logging"), so
	// verify records its outcome like delete and gc do.
	if err := s.store.Verify(r.Context(), h, sha256.New()); err != nil {
		slog.Info("viewer audit", "action", "object.verify", "hash", h, "valid", false)
		s.render(w, "result", "corrupt: "+template.HTMLEscapeString(err.Error()))
		return
	}
	slog.Info("viewer audit", "action", "object.verify", "hash", h, "valid", true)
	s.render(w, "result", "ok")
}

func (s *Server) deleteFragment(w http.ResponseWriter, r *http.Request) {
	h, ok := parseDigest(w, r)
	if !ok {
		return
	}
	if err := s.store.Delete(r.Context(), h); err != nil {
		s.render(w, "result", "delete failed")
		return
	}
	slog.Info("viewer audit", "action", "object.delete", "hash", h)
	s.render(w, "result", "deleted")
}

// --- gc ---

func (s *Server) gcPage(w http.ResponseWriter, r *http.Request) {
	s.render(w, "gc", struct{ CSRF string }{s.csrfFor(r)})
}

func (s *Server) gcFragment(w http.ResponseWriter, r *http.Request) {
	roots, err := parseDigestLines(r.FormValue("roots"))
	if err != nil {
		s.render(w, "result", "invalid root hash")
		return
	}
	reachable := make(map[string]bool, len(roots))
	for _, h := range roots {
		reachable[h.String()] = true
	}
	deleted, err := gcCount(r.Context(), s.store, reachable)
	if err != nil {
		s.render(w, "result", "gc failed")
		return
	}
	slog.Info("viewer audit", "action", "gc", "deleted", deleted)
	s.render(w, "result", fmt.Sprintf("gc: deleted %d objects", deleted))
}

func (s *Server) htmx(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/javascript")
	w.Write(htmxJS)
}

// gcCount deletes every object not in reachable and returns how many were
// deleted (stats delta; cas GC itself returns no count).
func gcCount(ctx context.Context, store *fs.Backend, reachable map[string]bool) (int64, error) {
	before, err := store.Stats(ctx)
	if err != nil {
		return 0, err
	}
	if err := store.GC(ctx, reachable); err != nil {
		return 0, err
	}
	after, err := store.Stats(ctx)
	if err != nil {
		return 0, err
	}
	return before.ObjectCount - after.ObjectCount, nil
}

// --- helpers ---

// render executes the named template into a buffer first, so a template error
// yields a clean 500 instead of a half-written 200.
func (s *Server) render(w http.ResponseWriter, name string, data any) {
	var buf bytes.Buffer
	if err := s.tmpl.ExecuteTemplate(&buf, name, data); err != nil {
		slog.Error("render", "template", name, "err", err)
		http.Error(w, "template error", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	if _, err := w.Write(buf.Bytes()); err != nil {
		slog.Error("render write", "template", name, "err", err)
	}
}

// previewLimit bounds the hexdump preview; larger objects are truncated.
const previewLimit = 256 << 10

// typePrefixLimit bounds the bytes read for envelope type sniffing: only the
// TLV header ([version][uvarint typeLen][type]) is needed, not the payload.
const typePrefixLimit = 4 << 10

// readN reads at most n bytes from the object at d.
func (s *Server) readN(ctx context.Context, d cas.Digest, n int64) ([]byte, error) {
	rc, err := s.store.Get(ctx, d)
	if err != nil {
		return nil, err
	}
	defer rc.Close()
	return io.ReadAll(io.LimitReader(rc, n))
}

// readPreview reads at most previewLimit bytes and reports whether the object
// was truncated.
func (s *Server) readPreview(ctx context.Context, d cas.Digest) ([]byte, bool, error) {
	data, err := s.readN(ctx, d, previewLimit+1)
	if err != nil {
		return nil, false, err
	}
	if len(data) > previewLimit {
		return data[:previewLimit], true, nil
	}
	return data, false, nil
}

// objectSize returns an object's size in bytes (0 when unavailable).
func (s *Server) objectSize(ctx context.Context, d cas.Digest) int64 {
	n, err := s.store.Size(ctx, d)
	if err != nil {
		return 0
	}
	return n
}

func (s *Server) objectType(ctx context.Context, d cas.Digest) string {
	data, err := s.readN(ctx, d, typePrefixLimit)
	if err != nil {
		return ""
	}
	return index.EnvelopeType(data)
}

func (s *Server) csrfFor(r *http.Request) string {
	if sess, ok := s.sessions.get(sessionID(r)); ok {
		return sess.CSRF
	}
	return ""
}

func (s *Server) roleFor(r *http.Request) string {
	if sess, ok := s.sessions.get(sessionID(r)); ok {
		return sess.Role
	}
	return ""
}

func parseDigest(w http.ResponseWriter, r *http.Request) (cas.Digest, bool) {
	d, err := sha256.Parse(r.PathValue("hash"))
	if err != nil {
		http.Error(w, "malformed hash", http.StatusBadRequest)
		return nil, false
	}
	return d, true
}

func parseDigestLines(s string) ([]cas.Digest, error) {
	var out []cas.Digest
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		d, err := sha256.Parse(line)
		if err != nil {
			return nil, err
		}
		out = append(out, d)
	}
	return out, nil
}

// shortDigest renders the first 8 hex chars of a digest for the FuncMap. The
// templates currently use the precomputed objectRow.Short field, so this stays
// registered for fragment templates that need to shorten a digest they hold as
// a string.
func shortDigest(d cas.Digest) string {
	if d.IsZero() {
		return ""
	}
	return sha256.Short(d)
}

// hexdump renders a classic 16-byte-row dump (offset, hex, ASCII).
func hexdump(data []byte) []dumpRow {
	var rows []dumpRow
	for off := 0; off < len(data); off += 16 {
		end := min(off+16, len(data))
		var hexParts []string
		var ascii strings.Builder
		for _, b := range data[off:end] {
			hexParts = append(hexParts, fmt.Sprintf("%02x", b))
			if b >= 32 && b < 127 {
				ascii.WriteByte(b)
			} else {
				ascii.WriteByte('.')
			}
		}
		rows = append(rows, dumpRow{fmt.Sprintf("%08x", off), strings.Join(hexParts, " "), ascii.String()})
	}
	return rows
}

type dumpRow struct {
	Offset string
	Hex    string
	ASCII  string
}

func callerIP(r *http.Request) string {
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil {
		return r.RemoteAddr
	}
	return host
}
